// Studio job processing (used by `animkit watch` and the tests).
//
//   jj_animstudio/data/inbox/<job>.json   written by the studio server (Lua)
//   jj_animstudio/data/outbox/<job>.json  result for the studio (always written, also on errors)
//   jj_animstudio/data/outbox/_watch.json heartbeat of this converter (stale = converter not running)
//   jj_animstudio/data/outbox/final/      final .ycd files + reports to copy into a target resource
//   jj_animstudio_stream/stream/<dict>.ycd streamed clips (previews jjs_<project>_v<n>, finals)
//
// Nothing from the inbox is trusted: job names, dict names and the document are validated again
// here, and every path is built from validated names only.

import fs from 'node:fs';
import path from 'node:path';
import { buildDocument } from '../../core/docbuild.mjs';
import { migrate } from '../../core/doc.mjs';
import { reportJson, reportMarkdown } from '../../core/report.mjs';

export const JOB_RE = /^[a-z0-9_]{1,64}$/;
export const PREVIEW_RE = /^jjs_[a-z0-9_]{1,40}_v\d{1,6}$/;
export const DICT_RE = /^[a-z0-9_]{1,48}$/;
export const KEEP_PREVIEWS = 5;
export const MAX_JOB_BYTES = 2 * 1024 * 1024 + 64 * 1024;
export const VERSION = '0.1.0';

export function studioPaths(studioDir, streamDir) {
  const data = path.join(studioDir, 'data');
  return {
    studio: studioDir, data, inbox: path.join(data, 'inbox'), outbox: path.join(data, 'outbox'),
    work: path.join(data, 'work'), final: path.join(data, 'outbox', 'final'),
    stream: streamDir, streamFiles: path.join(streamDir, 'stream'), heartbeat: path.join(data, 'outbox', '_watch.json'),
  };
}

export function writeJsonAtomic(file, obj) {
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, JSON.stringify(obj, null, 1));
  fs.renameSync(tmp, file);
}
function writeTextAtomic(file, text) {
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, file);
}

export const STREAM_MANIFEST = `-- GENERATED by animkit watch (jj_animstudio converter). Do not edit: it is rewritten when missing.
-- Holds the clips built by the in-game studio: previews (jjs_<project>_v<n>) and finished clips.
-- The studio restarts this resource after every build so clients receive the new .ycd files.
fx_version 'cerulean'
game 'gta5'
lua54 'yes'

name 'jj_animstudio_stream'
author 'JJ Scripts (generated)'
version '0.1.0'
description 'Generated stream resource of jj_animstudio (clip dictionaries only)'
`;

export function ensureFolders(P) {
  // SaveResourceFile cannot create folders: every folder the studio server writes into exists here.
  for (const d of [P.inbox, P.outbox, P.work, P.final, P.streamFiles, path.join(P.data, 'projects'), path.join(P.data, 'backups'), path.join(P.data, 'poses'), path.join(P.data, 'skeletons')]) fs.mkdirSync(d, { recursive: true });
  const man = path.join(P.stream, 'fxmanifest.lua');
  if (!fs.existsSync(man)) fs.writeFileSync(man, STREAM_MANIFEST);
}

// Keep the newest KEEP_PREVIEWS preview dictionaries (by modification time), never `keep`.
export function prunePreviews(P, keep) {
  const files = fs.readdirSync(P.streamFiles).filter((f) => f.endsWith('.ycd') && PREVIEW_RE.test(f.slice(0, -4)))
    .map((f) => ({ f, t: fs.statSync(path.join(P.streamFiles, f)).mtimeMs })).sort((a, b) => b.t - a.t);
  const removed = [];
  for (const { f } of files.filter((x) => x.f !== `${keep}.ycd`).slice(KEEP_PREVIEWS - 1)) {
    fs.unlinkSync(path.join(P.streamFiles, f));
    removed.push(f.slice(0, -4));
  }
  return removed;
}

const fail = (job, code, msg, extra = {}) => ({ job, ok: false, errors: [{ code, msg }], warnings: [], ...extra });

// Process one inbox file. Returns the result object (also written to the outbox) or null when
// the file is not complete yet (still being written).
export function processJobFile(P, file, { skeletons, skelInfo, workRoot, now = Date.now() } = {}) {
  const base = path.basename(file);
  const jobId = base.replace(/\.json$/, '');
  if (!JOB_RE.test(jobId)) {
    // Not ours to answer by name: drop it (cannot build a safe outbox path).
    try { fs.unlinkSync(file); } catch { /* gone */ }
    return { job: null, ok: false, errors: [{ code: 'job_name', msg: `Ungültiger Auftragsname ${base.slice(0, 80)}` }], dropped: true };
  }
  let stat;
  try { stat = fs.statSync(file); } catch { return null; }
  let result;
  if (stat.size > MAX_JOB_BYTES) result = fail(jobId, 'too_large', 'Der Auftrag ist größer als 2 MB.');
  else {
    let text;
    try { text = fs.readFileSync(file, 'utf8'); } catch { return null; }
    let job;
    try { job = JSON.parse(text); } catch (e) {
      if (now - stat.mtimeMs < 5000) return null;            // probably still being written
      result = fail(jobId, 'json_invalid', `Auftrag ist kein gültiges JSON (${e.message.slice(0, 80)}).`);
    }
    if (job && !result) result = runJob(P, jobId, job, { skeletons, skelInfo, workRoot });
  }
  try { fs.unlinkSync(file); } catch { /* already removed */ }
  result.finishedAt = new Date().toISOString();
  writeJsonAtomic(path.join(P.outbox, `${jobId}.json`), result);
  return result;
}

export function runJob(P, jobId, job, { skeletons, skelInfo, workRoot }) {
  if (!job || typeof job !== 'object') return fail(jobId, 'job_invalid', 'Auftrag ist leer.');
  const kind = job.kind;
  if (kind !== 'preview' && kind !== 'final') return fail(jobId, 'job_invalid', 'Unbekannte Auftragsart.');
  const dict = String(job.dict || '');
  if (!DICT_RE.test(dict)) return fail(jobId, 'name_invalid', `Ungültiger Dict-Name "${dict.slice(0, 60)}". Erlaubt: a-z, 0-9, _ (höchstens 48 Zeichen).`);
  if (kind === 'preview' && !PREVIEW_RE.test(dict)) return fail(jobId, 'name_invalid', 'Vorschau-Dicts müssen jjs_<projekt>_v<nummer> heißen.');
  if (kind === 'final' && PREVIEW_RE.test(dict)) return fail(jobId, 'name_invalid', 'Der Endname darf nicht wie eine Vorschau (jjs_..._vN) aussehen.');
  const m = migrate(job.doc);
  if (m.errors) return { job: jobId, kind, dict, ok: false, errors: m.errors, warnings: [] };
  const doc = m.doc;
  const workDir = path.join(workRoot, jobId);
  fs.rmSync(workDir, { recursive: true, force: true });
  fs.mkdirSync(workDir, { recursive: true });
  let r;
  try {
    r = buildDocument(doc, { skeletons, skelInfo, dict, workDir, streamDir: null });
  } catch (e) {
    r = { ok: false, errors: [{ code: 'internal', msg: `Interner Fehler im Konverter: ${e.message}` }], warnings: [] };
  }
  const out = {
    job: jobId, kind, dict, project: typeof job.project === 'string' ? job.project.slice(0, 40) : doc.name, ok: !!r.ok,
    errors: r.errors || [], warnings: r.warnings || [], clips: r.clips, origins: r.origins, duration: r.duration, frames: r.frames,
    loop: !!doc.loop, type: doc.type, events: r.registry?.events || [], light: r.light,
    findings: (r.findings || []).map((f) => ({ id: f.id, level: f.level, title: f.title, text: f.text, t: f.t, actor: f.actor })),
    readback: r.readback, timings: r.timings, registry: r.registry, skeletons: r.skeletons,
  };
  if (r.ok) {
    const dst = path.join(P.streamFiles, `${dict}.ycd`);
    fs.copyFileSync(r.ycdFile, `${dst}.tmp`);
    fs.renameSync(`${dst}.tmp`, dst);
    out.ycdBytes = r.ycdBytes;
    out.restart = true;
    if (kind === 'preview') out.pruned = prunePreviews(P, dict);
    if (kind === 'final') {
      fs.copyFileSync(r.ycdFile, path.join(P.final, `${dict}.ycd`));
      const target = typeof job.targetResource === 'string' && /^[A-Za-z0-9_-]{1,64}$/.test(job.targetResource) ? job.targetResource : null;
      const rep = reportJson(doc, { ...r, dict }, { targetResource: target });
      const md = reportMarkdown(rep);
      writeJsonAtomic(path.join(P.outbox, `${doc.name}.report.json`), rep);
      writeTextAtomic(path.join(P.outbox, `${doc.name}.report.md`), md);
      out.report = { md: `data/outbox/${doc.name}.report.md`, json: `data/outbox/${doc.name}.report.json`, ycd: `data/outbox/final/${dict}.ycd`, text: md.length <= 60000 ? md : md.slice(0, 60000) };
    }
  }
  fs.rmSync(workDir, { recursive: true, force: true });
  return out;
}

export function writeHeartbeat(P, extra = {}) {
  writeJsonAtomic(P.heartbeat, { ok: true, version: VERSION, pid: process.pid, time: Date.now(), iso: new Date().toISOString(), ...extra });
}
