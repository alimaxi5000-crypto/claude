-- Translate a key with optional string.format arguments. Missing keys fall back to German,
-- then to the key itself (never errors).
function L(key, ...)
    local lang = Locales[Config.Locale] or Locales.de
    local s = lang[key] or Locales.de[key] or key
    if select('#', ...) > 0 then
        local ok, res = pcall(string.format, s, ...)
        return ok and res or s
    end
    return s
end
